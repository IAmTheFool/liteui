namespace fs = std::filesystem;

struct TempDir
{
  fs::path path;
  explicit TempDir(const char *tag)
  {
    const auto stamp = std::chrono::steady_clock::now().time_since_epoch().count();
    path = fs::temp_directory_path() / (std::string("literoom_ic16_") + tag + "_" + std::to_string(stamp));
    fs::create_directories(path);
  }
  ~TempDir()
  {
    std::error_code ec;
    fs::remove_all(path, ec);
  }
  std::string file(const std::string &name) const { return u8ToString(path / fsPath(name)); }
};

template <size_t N>
static void writeBytes(const std::string &path, const uint8_t (&b)[N], size_t n = N)
{
  std::ofstream f(fsPath(path), std::ios::binary);
  f.write(reinterpret_cast<const char *>(b), static_cast<std::streamsize>(n));
}

template <size_t NP, size_t NE>
static void checkVector(const TempDir &d, const char *name, const uint8_t (&png)[NP], const uint16_t (&want)[NE], int w, int h)
{
  const std::string p = d.file(std::string(name) + ".png");
  writeBytes(p, png);
  std::string err;
  const auto img = decodeImage16(p, &err);
  if (!img)
  {
    std::printf("  [%s] decode failed: %s\n", name, err.c_str());
    CHECK(false);
    return;
  }
  CHECK(img->width == w && img->height == h && img->pixels.size() == NE);
  bool same = img->pixels.size() == NE;
  for (size_t i = 0; same && i < NE; ++i)
    same = img->pixels[i] == want[i];
  if (!same)
    std::printf("  [%s] samples differ\n", name);
  CHECK(same);
}

static void testHeaderParser()
{
  CHECK(!parsePngHeader(nullptr, 100).ok());
  CHECK(!parsePngHeader(kPng_RGBA16, 20).ok()); // too short
  const PngHeader a = parsePngHeader(kPng_RGBA16, sizeof kPng_RGBA16);
  CHECK(a.ok() && a.width == 3 && a.height == 2 && a.bitDepth == 16 && a.colorType == 6);
  const PngHeader b = parsePngHeader(kPng_RGB16, sizeof kPng_RGB16);
  CHECK(b.ok() && b.bitDepth == 16 && b.colorType == 2);
  const PngHeader g = parsePngHeader(kPng_GRAY16, sizeof kPng_GRAY16);
  CHECK(g.ok() && g.colorType == 0 && g.bitDepth == 16);
  const PngHeader e = parsePngHeader(kPng_RGBA8, sizeof kPng_RGBA8);
  CHECK(e.ok() && e.bitDepth == 8 && e.colorType == 6);
  const PngHeader i = parsePngHeader(kPng_INTER16, sizeof kPng_INTER16);
  CHECK(i.ok() && i.width == 5 && i.height == 4 && i.bitDepth == 16);
  // Damaged starts: bad signature, wrong first chunk, absurd values.
  uint8_t bad[33];
  std::copy(kPng_RGBA16, kPng_RGBA16 + 33, bad);
  uint8_t t[33];
  std::copy(bad, bad + 33, t);
  t[1] = 'X';
  CHECK(!parsePngHeader(t, 33).ok());
  std::copy(bad, bad + 33, t);
  t[12] = 'J';
  CHECK(!parsePngHeader(t, 33).ok());
  std::copy(bad, bad + 33, t);
  t[24] = 12; // bit depth 12 does not exist
  CHECK(!parsePngHeader(t, 33).ok());
  std::copy(bad, bad + 33, t);
  t[25] = 5; // neither does color type 5
  CHECK(!parsePngHeader(t, 33).ok());
  std::copy(bad, bad + 33, t);
  t[16] = t[17] = t[18] = t[19] = 0; // width 0
  CHECK(!parsePngHeader(t, 33).ok());
  // From a file: missing and non-PNG files are "not ok", not errors.
  TempDir d("hdr");
  CHECK(!readPngHeader(d.file("nope.png")).ok());
  {
    std::ofstream f(fsPath(d.file("text.png")));
    f << "this is not a png file at all, just some text of enough length";
  }
  CHECK(!readPngHeader(d.file("text.png")).ok());
  writeBytes(d.file("ok.png"), kPng_GRAYA16);
  const PngHeader ga = readPngHeader(d.file("ok.png"));
  CHECK(ga.ok() && ga.colorType == 4 && ga.bitDepth == 16 && ga.width == 3);
}

static void testDecodeVectors()
{
  TempDir d("vec");
  checkVector(d, "rgba16", kPng_RGBA16, kExp_RGBA16, 3, 2); // straight alpha, a transparent pixel keeps its color
  checkVector(d, "rgb16", kPng_RGB16, kExp_RGB16, 3, 2);    // no alpha channel: opaque
  checkVector(d, "gray16", kPng_GRAY16, kExp_GRAY16, 3, 2); // gray becomes R = G = B
  checkVector(d, "graya16", kPng_GRAYA16, kExp_GRAYA16, 3, 2);
  checkVector(d, "inter16", kPng_INTER16, kExp_INTER16, 5, 4); // Adam7 interlaced
  checkVector(d, "rgba8", kPng_RGBA8, kExp_RGBA8, 3, 2);       // not 16-bit: liteui's decoder, widened (v * 257)
}

static Image16 randomImage(int w, int h, uint32_t seed)
{
  Image16 im(w, h);
  std::mt19937 g(seed);
  for (uint16_t &v : im.pixels)
    v = static_cast<uint16_t>(g());
  return im;
}

static void testRoundTrip()
{
  TempDir d("rt");
  for (const auto &sz : {std::pair{1, 1}, std::pair{2, 3}, std::pair{37, 23}, std::pair{300, 200}, std::pair{1, 400}, std::pair{400, 1}})
  {
    Image16 im = randomImage(sz.first, sz.second, static_cast<uint32_t>(sz.first * 1000 + sz.second));
    im.pixels[0] = 0x1234; // a recognizable first sample
    if (im.pixels.size() >= 8)
    {
      im.pixels[3] = 0;     // a transparent pixel...
      im.pixels[4] = 65535; // ...next to extremes
      im.pixels[5] = 0;
      im.pixels[6] = 1;
      im.pixels[7] = 65535;
    }
    const std::string p = d.file("rt.png");
    std::string err;
    CHECK(encodePng16File(p, im, &err));
    const PngHeader h = readPngHeader(p);
    CHECK(h.ok() && h.bitDepth == 16 && h.colorType == 6 && static_cast<int>(h.width) == sz.first && static_cast<int>(h.height) == sz.second);
    const auto back = decodeImage16(p, &err);
    CHECK(back.has_value());
    if (back)
      CHECK(back->width == im.width && back->height == im.height && back->pixels == im.pixels); // every sample, alpha included
  }
}

// The encoder's byte order, checked against a decoder that is not ours: liteui's own (libpng strips a
// 16-bit sample to its HIGH byte; WIC rounds), so each 8-bit value must be within one of v / 257.
static void testEncoderByteOrder()
{
  TempDir d("order");
  Image16 im(16, 16);
  for (int i = 0; i < 16 * 16; ++i)
  {
    uint16_t *p = &im.pixels[static_cast<size_t>(i) * 4];
    p[0] = static_cast<uint16_t>(i * 257);                   // 0 .. 65535 in steps of 257
    p[1] = static_cast<uint16_t>(0x1200 + i);                // high byte 0x12, the low byte varies
    p[2] = static_cast<uint16_t>(0x0034 + (i % 7) * 0x2000); // low byte 0x34, the high byte varies
    p[3] = 65535;
  }
  const std::string p = d.file("order.png");
  CHECK(encodePng16File(p, im, nullptr));
  const auto eight = liteui_image::decodeFile(p, nullptr);
  CHECK(eight.has_value());
  if (!eight)
    return;
  CHECK(eight->width == 16 && eight->height == 16);
  for (int i = 0; i < 16 * 16; ++i)
    for (int c = 0; c < 3; ++c)
    {
      const double want = im.pixels[static_cast<size_t>(i) * 4 + static_cast<size_t>(c)] / 257.0;
      CHECK_NEAR(eight->pixels[static_cast<size_t>(i) * 4 + static_cast<size_t>(c)], want, 1.01);
    }
}

static void testFallbackIsTheEightBitDecoder()
{
  // An 8-bit PNG goes through liteui's decoder and is widened: exactly the editor's pixels.
  TempDir d("fb");
  const std::string p = d.file("eight.png");
  writeBytes(p, kPng_RGBA8);
  const auto direct = liteui_image::decodeFile(p, nullptr);
  const auto wide = decodeImage16(p, nullptr);
  CHECK(direct && wide && direct->pixels.size() == wide->pixels.size());
  if (direct && wide)
    for (size_t i = 0; i < wide->pixels.size(); ++i)
      CHECK(wide->pixels[i] == direct->pixels[i] * 257);
  // And a 16-bit file read through the editor's 8-bit decoder is the narrowed form of the 16-bit read.
  const std::string q = d.file("sixteen.png");
  writeBytes(q, kPng_RGBA16);
  const auto d8 = liteui_image::decodeFile(q, nullptr);
  const auto d16 = decodeImage16(q, nullptr);
  CHECK(d8 && d16 && d8->pixels.size() == d16->pixels.size());
  if (d8 && d16)
    for (size_t i = 0; i < d16->pixels.size(); ++i)
      CHECK_NEAR(d8->pixels[i], d16->pixels[i] / 257.0, 1.01);
}

static void testErrors()
{
  TempDir d("err");
  std::string err;
  CHECK(!decodeImage16(d.file("missing.png"), &err).has_value() && !err.empty());
  CHECK(!decodeImage16(d.file("missing.png"), nullptr).has_value()); // null error out is fine
  {
    std::ofstream f(fsPath(d.file("junk.png")));
    f << "not a png, but long enough to have a header, honestly yes";
  }
  err.clear();
  CHECK(!decodeImage16(d.file("junk.png"), &err).has_value() && !err.empty());
  // A 16-bit PNG cut off in the middle of its data: an error, not a crash, and nothing returned.
  for (size_t keep : {size_t{40}, size_t{60}, sizeof kPng_RGBA16 - 20})
  {
    writeBytes(d.file("cut.png"), kPng_RGBA16, keep);
    err.clear();
    const auto r = decodeImage16(d.file("cut.png"), &err);
    CHECK(!r.has_value() && !err.empty());
  }
  // The header says 16-bit but the file is 8-bit-sized garbage afterwards.
  {
    uint8_t buf[60];
    std::copy(kPng_RGBA16, kPng_RGBA16 + 60, buf);
    for (size_t i = 41; i < 60; ++i)
      buf[i] = static_cast<uint8_t>(0xA5 ^ i);
    writeBytes(d.file("garbage.png"), buf);
    CHECK(!decodeImage16(d.file("garbage.png"), &err).has_value());
  }
  // Writing: bad folder, empty picture, a picture whose buffer is too small.
  const Image16 im = randomImage(4, 4, 3);
  err.clear();
  CHECK(!encodePng16File(d.file("no_such_dir/x.png"), im, &err) && !err.empty());
  CHECK(!encodePng16File(d.file("no_such_dir/x.png"), im, nullptr));
  err.clear();
  CHECK(!encodePng16File(d.file("empty.png"), Image16(), &err) && !err.empty());
  Image16 shortBuf(4, 4);
  shortBuf.pixels.resize(10);
  CHECK(!encodePng16File(d.file("short.png"), shortBuf, nullptr));
  CHECK(!fs::exists(fsPath(d.file("empty.png"))) && !fs::exists(fsPath(d.file("short.png"))));
}

static void testConversions()
{
  CanvasImage c(5, 3);
  for (size_t i = 0; i < c.pixels.size(); ++i)
    c.pixels[i] = static_cast<uint8_t>(i * 5 + 1);
  const Image16 w = widenImage(c);
  CHECK(w.width == 5 && w.height == 3 && w.pixels.size() == c.pixels.size());
  for (size_t i = 0; i < c.pixels.size(); ++i)
    CHECK(w.pixels[i] == c.pixels[i] * 257);
  const CanvasImage back = narrowImage(w);
  CHECK(back.width == 5 && back.height == 3 && back.pixels == c.pixels);
  CHECK(widenImage(CanvasImage()).empty() && narrowImage(Image16()).pixels.empty());
  // 16-bit values between two 8-bit levels narrow to the nearest.
  Image16 f(1, 1);
  f.pixels = {128, 129, 385, 65535};
  const CanvasImage n = narrowImage(f);
  CHECK(n.pixels[0] == 0 && n.pixels[1] == 1 && n.pixels[2] == 1 && n.pixels[3] == 255); // 128/257 = 0.498, 129/257 = 0.502, 385/257 = 1.498
}

// The color tags of a source travel into a 16-bit export without touching a sample: the chunks go in
// right after IHDR (io/color_tag.hpp), and both the 16-bit decoder and liteui's 8-bit one still read it.
static void testColorTagsSurviveTheEncoder()
{
  TempDir d("tags");
  const Image16 im = randomImage(37, 23, 5);
  std::string err;
  // A tagged source PNG: encode, then give it a profile chunk.
  const std::string src = d.file("src.png");
  CHECK(encodePng16File(src, im, &err));
  color_tag::PngColor tags;
  const std::string name = "Display P3 test";
  tags.iccp.assign(name.begin(), name.end());
  tags.iccp.push_back(0); // end of the name
  tags.iccp.push_back(0); // compression method
  const std::vector<uint8_t> profile(300, 0x42);
  const std::vector<uint8_t> z = color_tag::zlibStored(profile.data(), profile.size());
  tags.iccp.insert(tags.iccp.end(), z.begin(), z.end());
  CHECK(color_tag::insertColorIntoFile(src, tags));
  const auto tagged = decodeImage16(src, &err);
  CHECK(tagged.has_value() && tagged->pixels == im.pixels); // a tagged file decodes to the same samples

  // The export: untagged out of the encoder, tagged after carrying the source's tags.
  const std::string out = d.file("out.png");
  CHECK(encodePng16File(out, im, &err));
  CHECK(color_tag::colorTagOf(out).text == "untagged (assumed sRGB)");
  CHECK(color_tag::carryColorToPng(out, src) == "Display P3 test (embedded profile, not sRGB)");
  const auto back = decodeImage16(out, &err);
  CHECK(back.has_value() && back->pixels == im.pixels);
  const PngHeader h = readPngHeader(out);
  CHECK(h.ok() && h.bitDepth == 16 && h.colorType == 6 && h.width == 37 && h.height == 23);
  const auto narrow = liteui_image::decodeFile(out, &err); // liteui's decoder reads the tagged file too
  CHECK(narrow.has_value() && narrow->width == 37 && narrow->height == 23);
  CHECK(color_tag::colorTagOf(out).text == color_tag::colorTagOf(src).text);
}

